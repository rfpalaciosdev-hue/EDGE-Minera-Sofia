"""Read mounted files only. Invoked by the Windows collector in a temporary container.

No Docker socket, network, credentials or database volume are needed.
Sizes are logical file bytes, not allocated filesystem blocks.
"""
import base64
import fnmatch
import json
import os
import stat
from pathlib import Path


def directory_bytes(path, pattern=None):
    root = Path(path)
    if not root.is_dir():
        return None
    total = 0
    seen = set()

    def fail(error):
        raise error

    try:
        for directory, _, files in os.walk(root, followlinks=False, onerror=fail):
            for name in files:
                if pattern and not fnmatch.fnmatchcase(name, pattern):
                    continue
                try:
                    info = (Path(directory) / name).lstat()
                except FileNotFoundError:
                    # Log rotation can remove a file during a scan.
                    continue
                key = (info.st_dev, info.st_ino)
                if stat.S_ISREG(info.st_mode) and key not in seen:
                    seen.add(key)
                    total += info.st_size
        return total
    except OSError:
        return None


def collect(spec):
    result = {}
    for item in spec:
        # Paths are generated by the host collector; restrict reads to its mounts.
        path = Path(item["path"])
        if not path.is_relative_to("/probe") or ".." in path.parts:
            raise ValueError("Invalid probe path")
        result[item["key"]] = directory_bytes(path, item.get("pattern"))
    return result


if __name__ == "__main__":
    spec = json.loads(base64.b64decode(os.environ["EDGE_STORAGE_SPEC_B64"]))
    print(json.dumps(collect(spec), allow_nan=False))
